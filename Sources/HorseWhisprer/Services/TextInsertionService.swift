import AppKit
import ApplicationServices
import Foundation

struct TextInsertionPasteboardSnapshotItem: Sendable {
    let entries: [(type: NSPasteboard.PasteboardType, data: Data)]
}

protocol TextInsertionPasteboardControlling: AnyObject {
    var changeCount: Int { get }
    func snapshotItems() -> [TextInsertionPasteboardSnapshotItem]
    func contains(text: String) -> Bool
    func copy(text: String)
    func copyTransient(text: String)
    func restoreItems(_ items: [TextInsertionPasteboardSnapshotItem])
}

extension TextInsertionPasteboardControlling {
    /// Copies text that only passes through the clipboard on its way to a paste.
    /// Conformers that can mark it for clipboard managers override this.
    func copyTransient(text: String) {
        copy(text: text)
    }

    func contains(text: String) -> Bool {
        let items = snapshotItems()
        guard items.count == 1,
              let entry = items[0].entries.first(where: { $0.type == .string }) else { return false }
        return String(data: entry.data, encoding: .utf8) == text
    }
}

protocol TextInsertionEventDispatching: AnyObject {
    func sendPasteShortcut() -> PasteDispatchResult
    @MainActor func sendRemotePasteShortcut(canDeliver: @MainActor () -> Bool) async -> PasteDispatchResult
    func type(text: String) -> Bool
}

struct PasteDispatchResult: Equatable, Sendable {
    let sourceCreated: Bool
    let eventsCreated: Bool
    let posted: Bool
}

final class SystemTextInsertionPasteboard: TextInsertionPasteboardControlling {
    private let pasteboard: NSPasteboard

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var changeCount: Int {
        pasteboard.changeCount
    }

    func snapshotItems() -> [TextInsertionPasteboardSnapshotItem] {
        (pasteboard.pasteboardItems ?? []).map { item in
            let entries = item.types.compactMap { type -> (NSPasteboard.PasteboardType, Data)? in
                guard let data = item.data(forType: type) else {
                    return nil
                }

                return (type, data)
            }

            return TextInsertionPasteboardSnapshotItem(entries: entries)
        }
    }

    func contains(text: String) -> Bool {
        pasteboard.string(forType: .string) == text
    }

    func copy(text: String) {
        // Fully populate the item before publishing it to clipboard observers.
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
    }

    /// The nspasteboard.org markers tell clipboard managers not to record text
    /// that is about to be pasted and then replaced by the previous clipboard.
    func copyTransient(text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: Self.transientType)
        pasteboard.setData(Data(), forType: Self.autoGeneratedType)
    }

    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    func restoreItems(_ items: [TextInsertionPasteboardSnapshotItem]) {
        pasteboard.clearContents()

        guard !items.isEmpty else {
            return
        }

        let restoredItems = items.map { snapshot -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in snapshot.entries {
                item.setData(entry.data, forType: entry.type)
            }
            return item
        }

        pasteboard.writeObjects(restoredItems)
    }
}

final class QuartzTextInsertionEventDispatcher: TextInsertionEventDispatching {
    private let postEvent: (CGEvent) -> Void
    private let pause: @MainActor (UInt64) async -> Void

    init(postEvent: @escaping (CGEvent) -> Void = { $0.post(tap: .cghidEventTap) },
         pause: @escaping @MainActor (UInt64) async -> Void = { try? await Task.sleep(nanoseconds: $0) }) {
        self.postEvent = postEvent
        self.pause = pause
    }

    /// Remote clients may forward modifier transitions rather than the flags on V.
    /// Prepare the whole chord first, and always release Command, even if canceled.
    @MainActor
    func sendRemotePasteShortcut(canDeliver: @MainActor () -> Bool) async -> PasteDispatchResult {
        guard let source = CGEventSource(stateID: .combinedSessionState) else {
            return PasteDispatchResult(sourceCreated: false, eventsCreated: false, posted: false)
        }
        guard let commandDown = CGEvent(keyboardEventSource: source, virtualKey: 55, keyDown: true),
              let commandUp = CGEvent(keyboardEventSource: source, virtualKey: 55, keyDown: false),
              let down = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: false) else {
            return PasteDispatchResult(sourceCreated: true, eventsCreated: false, posted: false)
        }
        // A remote client may inspect the physical left/right modifier flags.
        // maskCommand alone says Command is active but identifies neither key.
        // NX_DEVICELCMDKEYMASK (IOLLEvent.h) corresponds to virtual key 55.
        let leftCommand = CGEventFlags.maskCommand.union(CGEventFlags(rawValue: 0x00000008))
        commandDown.type = .flagsChanged
        commandDown.flags = leftCommand
        commandUp.type = .flagsChanged
        commandUp.flags = []
        down.flags = leftCommand
        up.flags = leftCommand
        let skipped = PasteDispatchResult(sourceCreated: true, eventsCreated: true, posted: false)
        guard !Task.isCancelled, canDeliver() else { return skipped }
        postEvent(commandDown)
        defer { postEvent(commandUp) }
        await pause(30_000_000)
        guard !Task.isCancelled, canDeliver() else { return skipped }
        postEvent(down)
        postEvent(up)
        await pause(30_000_000)
        return PasteDispatchResult(sourceCreated: true, eventsCreated: true, posted: true)
    }

    func sendPasteShortcut() -> PasteDispatchResult {
        guard let source = CGEventSource(stateID: .combinedSessionState) else {
            return PasteDispatchResult(sourceCreated: false, eventsCreated: false, posted: false)
        }

        guard let down = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: false) else {
            return PasteDispatchResult(sourceCreated: true, eventsCreated: false, posted: false)
        }

        down.flags = .maskCommand
        up.flags = .maskCommand
        postEvent(down)
        postEvent(up)
        return PasteDispatchResult(sourceCreated: true, eventsCreated: true, posted: true)
    }

    func type(text: String) -> Bool {
        guard let source = CGEventSource(stateID: .combinedSessionState) else {
            return false
        }

        // One event per Character keeps surrogate pairs and combined emoji whole.
        for character in text {
            let units = Array(String(character).utf16)
            guard let down = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
                  let up = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false) else {
                return false
            }

            units.withUnsafeBufferPointer { pointer in
                down.keyboardSetUnicodeString(stringLength: units.count, unicodeString: pointer.baseAddress)
                up.keyboardSetUnicodeString(stringLength: units.count, unicodeString: pointer.baseAddress)
            }
            down.post(tap: .cghidEventTap)
            up.post(tap: .cghidEventTap)
        }

        return true
    }
}

@MainActor
final class TextInsertionService {
    struct TrackedApplication {
        let localizedName: String?
        let bundleIdentifier: String?
        private let isTerminatedProvider: @MainActor () -> Bool
        private let activateHandler: @MainActor () -> Void

        init(
            localizedName: String?,
            bundleIdentifier: String?,
            isTerminated: @escaping @MainActor () -> Bool = { false },
            activate: @escaping @MainActor () -> Void = {}
        ) {
            self.localizedName = localizedName
            self.bundleIdentifier = bundleIdentifier
            self.isTerminatedProvider = isTerminated
            self.activateHandler = activate
        }

        init(application: NSRunningApplication) {
            localizedName = application.localizedName
            bundleIdentifier = application.bundleIdentifier
            isTerminatedProvider = { application.isTerminated }
            activateHandler = { application.activate() }
        }

        @MainActor
        var isTerminated: Bool {
            isTerminatedProvider()
        }

        @MainActor
        func activate() {
            activateHandler()
        }
    }

    private struct RestorationContext {
        let targetApplication: TrackedApplication?
        let frontmostApplication: TrackedApplication?
        let restoreAttempted: Bool
        let waitedForFocusSettle: Bool
    }

    private struct CopyResult {
        let beforeChangeCount: Int
        let afterChangeCount: Int
    }

    private let delayedPasteTargetValidator: @MainActor () -> (@MainActor () -> Bool)?
    private let refreshRemoteClipboard: @MainActor (@MainActor () -> Bool) async -> Bool
    private let ownBundleIdentifier: String?
    private let frontmostApplicationProvider: () -> TrackedApplication?
    private let pasteboard: any TextInsertionPasteboardControlling
    private let eventDispatcher: any TextInsertionEventDispatching
    private let diagnostics: any InsertionDiagnosticsLogging
    private let sleep: @Sendable (UInt64) async -> Void
    private let focusSettleDelayNanoseconds: UInt64
    private let pasteboardRestoreDelayNanoseconds: UInt64
    private var activationObserver: NSObjectProtocol?
    private var lastExternalApplication: TrackedApplication?
    private var targetsOwnWindow = false
    private var pendingPasteboardRestore: (items: [TextInsertionPasteboardSnapshotItem], changeCount: Int)?
    var onInsertionAttempt: ((InsertionAttemptRecord) -> Void)?
    /// Returns true when the user is typing in one of Horse Whisprer's own text
    /// fields, so dictation should land there instead of in the previous app.
    var ownTextTargetProvider: (() -> Bool)?

    /// Display name of the app the next insertion will go to.
    var currentTargetName: String? {
        if targetsOwnWindow { return "Horse Whisprer" }
        return lastExternalApplication?.localizedName ?? lastExternalApplication?.bundleIdentifier
    }

    init(
        workspace: NSWorkspace = .shared,
        ownBundleIdentifier: String? = Bundle.main.bundleIdentifier,
        frontmostApplicationProvider: (() -> TrackedApplication?)? = nil,
        pasteboard: any TextInsertionPasteboardControlling = SystemTextInsertionPasteboard(),
        eventDispatcher: any TextInsertionEventDispatching = QuartzTextInsertionEventDispatcher(),
        diagnostics: any InsertionDiagnosticsLogging = InsertionDiagnostics.shared,
        sleep: @escaping @Sendable (UInt64) async -> Void = { delay in
            try? await Task.sleep(nanoseconds: delay)
        },
        focusSettleDelayNanoseconds: UInt64 = 100_000_000,
        pasteboardRestoreDelayNanoseconds: UInt64 = 400_000_000,
        delayedPasteTargetValidator: @escaping @MainActor () -> (@MainActor () -> Bool)? = TextInsertionService.capturePasteWindow,
        refreshRemoteClipboard: @escaping @MainActor (@MainActor () -> Bool) async -> Bool = RemoteClipboardFocusRefresh.refresh,
        observeWorkspaceNotifications: Bool = true
    ) {
        self.delayedPasteTargetValidator = delayedPasteTargetValidator
        self.refreshRemoteClipboard = refreshRemoteClipboard
        self.frontmostApplicationProvider = frontmostApplicationProvider ?? {
            guard let application = workspace.frontmostApplication else {
                return nil
            }

            return TrackedApplication(application: application)
        }
        self.pasteboard = pasteboard
        self.eventDispatcher = eventDispatcher
        self.diagnostics = diagnostics
        self.sleep = sleep
        self.focusSettleDelayNanoseconds = focusSettleDelayNanoseconds
        self.pasteboardRestoreDelayNanoseconds = pasteboardRestoreDelayNanoseconds
        self.ownBundleIdentifier = ownBundleIdentifier

        if let frontmostApplication = self.frontmostApplicationProvider(),
           frontmostApplication.bundleIdentifier != ownBundleIdentifier {
            lastExternalApplication = frontmostApplication
        }

        if observeWorkspaceNotifications {
            activationObserver = workspace.notificationCenter.addObserver(
                forName: NSWorkspace.didActivateApplicationNotification,
                object: workspace,
                queue: .main
            ) { [weak self] notification in
                guard let application = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication else {
                    return
                }

                Task { @MainActor [weak self] in
                    self?.remember(application: TrackedApplication(application: application))
                }
            }
        }
    }

    func captureInsertionTarget() {
        targetsOwnWindow = ownTextTargetProvider?() ?? false
        if let frontmostApplication = frontmostApplicationProvider() {
            remember(application: frontmostApplication)
        }
    }

    /// Brings the last external app back to the front, for example after the
    /// menu bar popover took focus, so dictation starts in the user's text field.
    func returnFocusToTarget() async {
        _ = await restoreInsertionTargetIfNeeded()
    }

    /// Manual retries and the setup test must use the target app's preferences too.
    func insert(text: String, settings: AppSettings) async -> InsertionOutcome {
        captureInsertionTarget()
        // These actions explicitly insert into the previous external app, even
        // when History's search field is still the first responder.
        targetsOwnWindow = false
        let bundle = lastExternalApplication?.bundleIdentifier
        let behavior = settings.insertBehavior(for: bundle)
        let timing = settings.pasteTiming(for: bundle)
        if behavior == .pasteThenType, timing != .standard {
            _ = await restoreInsertionTargetIfNeeded()
        }
        return await insert(text: text, behavior: behavior, pasteTiming: timing,
                            expectedBundleIdentifier: bundle, canDeliver: { !Task.isCancelled })
    }

    /// Explicit copies cancel restoration of an earlier temporary paste.
    @discardableResult
    func copyToClipboard(_ text: String) -> Bool {
        let copy = copyToPasteboard(text)
        return pasteboard.changeCount == copy.afterChangeCount && pasteboard.contains(text: text)
    }

    func insert(text: String, behavior: InsertBehavior) async -> InsertionOutcome {
        let attemptedAt = Date()
        let restoration = await restoreInsertionTargetIfNeeded()
        // Only the session that captured our own window as its target keeps it.
        targetsOwnWindow = false

        switch behavior {
        case .copyOnly:
            let copy = copyToPasteboard(text)
            let outcome: InsertionOutcome = .copiedOnly
            publish(record: buildAttemptRecord(
                attemptedAt: attemptedAt,
                behavior: behavior,
                restoration: restoration,
                pasteboardCopy: copy,
                pasteResult: PasteDispatchResult(sourceCreated: false, eventsCreated: false, posted: false),
                typingAttempted: false,
                finalPath: .copyOnly,
                outcome: outcome
            ))
            return outcome
        case .typeOnly:
            let typed = eventDispatcher.type(text: text)
            let outcome: InsertionOutcome = typed ? .typed : .failed("typing failed")
            publish(record: buildAttemptRecord(
                attemptedAt: attemptedAt,
                behavior: behavior,
                restoration: restoration,
                pasteboardCopy: nil,
                pasteResult: PasteDispatchResult(sourceCreated: false, eventsCreated: false, posted: false),
                typingAttempted: true,
                finalPath: typed ? .typeOnlyTyped : .typeOnlyFailed,
                outcome: outcome
            ))
            return outcome
        case .pasteThenType:
            // A previous paste may still own the clipboard. Carry its original
            // backup forward instead of saving a temporary transcript as user data.
            let backup: [TextInsertionPasteboardSnapshotItem]
            if let pending = pendingPasteboardRestore, pending.changeCount == pasteboard.changeCount {
                backup = pending.items
            } else {
                backup = pasteboard.snapshotItems()
            }
            let copy = copyToPasteboard(text, transient: true)
            let pasteResult = eventDispatcher.sendPasteShortcut()
            schedulePasteboardRestore(backup, insertedChangeCount: copy.afterChangeCount)

            if pasteResult.posted {
                let outcome: InsertionOutcome = .pasted
                publish(record: buildAttemptRecord(
                    attemptedAt: attemptedAt,
                    behavior: behavior,
                    restoration: restoration,
                    pasteboardCopy: copy,
                    pasteResult: pasteResult,
                    typingAttempted: false,
                    finalPath: .pasteCommandPosted,
                    outcome: outcome
                ))
                return outcome
            }

            if eventDispatcher.type(text: text) {
                let outcome: InsertionOutcome = .typed
                publish(record: buildAttemptRecord(
                    attemptedAt: attemptedAt,
                    behavior: behavior,
                    restoration: restoration,
                    pasteboardCopy: copy,
                    pasteResult: pasteResult,
                    typingAttempted: true,
                    finalPath: .typedFallbackUsed,
                    outcome: outcome
                ))
                return outcome
            }

            _ = copyToPasteboard(text)
            let outcome: InsertionOutcome = .copiedOnly
            publish(record: buildAttemptRecord(
                attemptedAt: attemptedAt,
                behavior: behavior,
                restoration: restoration,
                pasteboardCopy: copy,
                pasteResult: pasteResult,
                typingAttempted: true,
                finalPath: .copiedOnlyFallback,
                outcome: outcome
            ))
            return outcome
        }
    }

    /// Remote clipboard delivery is deliberately a single paste attempt. It cannot
    /// verify remote text, so never type a second copy after dispatching Cmd-V.
    func insert(text: String, behavior: InsertBehavior, pasteTiming: ClipboardPasteTiming,
                expectedBundleIdentifier: String?, canDeliver: @MainActor () -> Bool) async -> InsertionOutcome {
        guard behavior == .pasteThenType, pasteTiming != .standard else {
            return await insert(text: text, behavior: behavior)
        }
        let attemptedAt = Date()
        let target = frontmostApplicationProvider()
        let restoration = RestorationContext(targetApplication: target, frontmostApplication: target,
                                             restoreAttempted: false, waitedForFocusSettle: false)
        let stillInWindow = delayedPasteTargetValidator()
        // Leave an ordinary copy available to remote clipboard sharing, without
        // transient markers or the local-only clipboard restoration timer.
        let copy = copyToPasteboard(text)
        let ownsCompleteTranscript = {
            self.pasteboard.changeCount == copy.afterChangeCount && self.pasteboard.contains(text: text)
        }
        var paste = PasteDispatchResult(sourceCreated: false, eventsCreated: false, posted: false)
        if let expectedBundleIdentifier,
           target?.bundleIdentifier == expectedBundleIdentifier,
           let stillInWindow, stillInWindow(), canDeliver(), !Task.isCancelled,
           ownsCompleteTranscript() {
            // ARD can retain the first remote clipboard while it stays active.
            // Re-enter the app after publishing each transcript to trigger sharing.
            var refreshed = true
            if expectedBundleIdentifier == "com.apple.RemoteDesktop" {
                refreshed = await refreshRemoteClipboard { canDeliver() && !Task.isCancelled && ownsCompleteTranscript() }
                AudioDiagnostics.shared.log("RemoteClipboard", "handoff=\(refreshed) targetMatches=\(frontmostApplicationProvider()?.bundleIdentifier == expectedBundleIdentifier) windowMatches=\(stillInWindow()) clipboardMatches=\(ownsCompleteTranscript())")
            }
            let delay = expectedBundleIdentifier == "com.apple.RemoteDesktop"
                ? max(pasteTiming.delayNanoseconds, 2_000_000_000)
                : pasteTiming.delayNanoseconds
            if refreshed { await sleep(delay) }
            if refreshed, canDeliver(), !Task.isCancelled,
               frontmostApplicationProvider()?.bundleIdentifier == expectedBundleIdentifier,
               stillInWindow(), ownsCompleteTranscript() {
                paste = await eventDispatcher.sendRemotePasteShortcut {
                    canDeliver() && !Task.isCancelled
                        && frontmostApplicationProvider()?.bundleIdentifier == expectedBundleIdentifier
                        && stillInWindow() && ownsCompleteTranscript()
                }
            }
        }
        let outcome: InsertionOutcome = paste.posted ? .pasted
            : (ownsCompleteTranscript() ? .copiedOnly : .failed("Clipboard changed. Copy the full transcript from History."))
        publish(record: buildAttemptRecord(attemptedAt: attemptedAt, behavior: behavior,
            restoration: restoration, pasteboardCopy: copy, pasteResult: paste, typingAttempted: false,
            finalPath: paste.posted ? .pasteCommandPosted : .copiedOnlyFallback, outcome: outcome))
        return outcome
    }

    /// Accessibility need only expose the local window, not the remote text field.
    static func capturePasteWindow() -> (@MainActor () -> Bool)? {
        guard let app = NSWorkspace.shared.frontmostApplication else { return nil }
        let pid = app.processIdentifier
        let application = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(application, 0.2)
        func focusedWindow() -> AXUIElement? {
            var value: CFTypeRef?
            guard AXUIElementCopyAttributeValue(application, kAXFocusedWindowAttribute as CFString, &value) == .success,
                  let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
            return (value as! AXUIElement)
        }
        guard let window = focusedWindow() else { return nil }
        return {
            guard NSWorkspace.shared.frontmostApplication?.processIdentifier == pid,
                  let current = focusedWindow() else { return false }
            return CFEqual(window, current)
        }
    }

    private func copyToPasteboard(_ text: String, transient: Bool = false) -> CopyResult {
        if !transient { pendingPasteboardRestore = nil }
        let beforeChangeCount = pasteboard.changeCount
        if transient {
            pasteboard.copyTransient(text: text)
        } else {
            pasteboard.copy(text: text)
        }
        return CopyResult(beforeChangeCount: beforeChangeCount, afterChangeCount: pasteboard.changeCount)
    }

    private func schedulePasteboardRestore(
        _ items: [TextInsertionPasteboardSnapshotItem],
        insertedChangeCount: Int
    ) {
        pendingPasteboardRestore = (items, insertedChangeCount)
        Task { @MainActor [weak self] in
            guard let self else {
                return
            }

            await sleep(pasteboardRestoreDelayNanoseconds)
            // Only the latest paste may restore or clear the shared backup.
            guard pendingPasteboardRestore?.changeCount == insertedChangeCount else { return }
            pendingPasteboardRestore = nil
            guard pasteboard.changeCount == insertedChangeCount else {
                return
            }

            pasteboard.restoreItems(items)
        }
    }

    private func restoreInsertionTargetIfNeeded() async -> RestorationContext {
        let frontmostApplication = frontmostApplicationProvider()
        if targetsOwnWindow {
            return RestorationContext(
                targetApplication: frontmostApplication,
                frontmostApplication: frontmostApplication,
                restoreAttempted: false,
                waitedForFocusSettle: false
            )
        }
        guard let application = lastExternalApplication,
              !application.isTerminated,
              application.bundleIdentifier != ownBundleIdentifier else {
            return RestorationContext(
                targetApplication: lastExternalApplication,
                frontmostApplication: frontmostApplication,
                restoreAttempted: false,
                waitedForFocusSettle: false
            )
        }

        guard application.bundleIdentifier != frontmostApplication?.bundleIdentifier else {
            return RestorationContext(
                targetApplication: application,
                frontmostApplication: frontmostApplication,
                restoreAttempted: false,
                waitedForFocusSettle: false
            )
        }

        application.activate()
        var waitedForFocusSettle = false
        if focusSettleDelayNanoseconds > 0 {
            waitedForFocusSettle = true
            await sleep(focusSettleDelayNanoseconds)
        }

        return RestorationContext(
            targetApplication: application,
            frontmostApplication: frontmostApplication,
            restoreAttempted: true,
            waitedForFocusSettle: waitedForFocusSettle
        )
    }

    private func buildAttemptRecord(
        attemptedAt: Date,
        behavior: InsertBehavior,
        restoration: RestorationContext,
        pasteboardCopy: CopyResult?,
        pasteResult: PasteDispatchResult,
        typingAttempted: Bool,
        finalPath: InsertionExecutionPath,
        outcome: InsertionOutcome
    ) -> InsertionAttemptRecord {
        InsertionAttemptRecord(
            attemptedAt: attemptedAt,
            requestedBehavior: behavior,
            targetApplicationName: restoration.targetApplication?.localizedName,
            targetBundleIdentifier: restoration.targetApplication?.bundleIdentifier,
            frontmostApplicationName: restoration.frontmostApplication?.localizedName,
            frontmostBundleIdentifier: restoration.frontmostApplication?.bundleIdentifier,
            restoreAttempted: restoration.restoreAttempted,
            waitedForFocusSettle: restoration.waitedForFocusSettle,
            focusSettleDelayMilliseconds: restoration.waitedForFocusSettle ? Int(focusSettleDelayNanoseconds / 1_000_000) : 0,
            pasteboardChangeCountBeforeCopy: pasteboardCopy?.beforeChangeCount,
            pasteboardChangeCountAfterCopy: pasteboardCopy?.afterChangeCount,
            pasteEventSourceCreated: pasteResult.sourceCreated,
            pasteEventsCreated: pasteResult.eventsCreated,
            pasteEventPosted: pasteResult.posted,
            typingAttempted: typingAttempted,
            finalPath: finalPath,
            outcome: outcome
        )
    }

    private func publish(record: InsertionAttemptRecord) {
        diagnostics.log(record)
        onInsertionAttempt?(record)
    }

    private func remember(application: TrackedApplication) {
        guard application.bundleIdentifier != ownBundleIdentifier else {
            return
        }

        lastExternalApplication = application
    }
}

/// ARD's automatic sharing refreshes on activation. Keep this workaround local
/// to ARD, preserve its sharing setting, and never reclaim focus from a third app.
@MainActor
enum RemoteClipboardFocusRefresh {
    static func refresh(canContinue: @MainActor () -> Bool) async -> Bool {
        let workspace = NSWorkspace.shared
        guard let target = workspace.frontmostApplication,
              target.bundleIdentifier == "com.apple.RemoteDesktop" else { return false }
        let own = NSRunningApplication.current
        return await cycle(
            targetPID: target.processIdentifier, ownPID: own.processIdentifier,
            frontmostPID: { workspace.frontmostApplication?.processIdentifier },
            activateOwn: {
                // The ordinary running-application request may be denied while
                // ARD is active. This is our own app's user-triggered activation.
                NSApp.activate(ignoringOtherApps: true)
                return true
            }, activateTarget: {
                // Cooperatively hand activation back instead of making another
                // uncoordinated request from a background menu bar application.
                NSApp.yieldActivation(to: target)
                return target.activate(from: own, options: [])
            },
            canContinue: { canContinue() && !target.isTerminated },
            pause: { try? await Task.sleep(nanoseconds: $0) },
            diagnose: { AudioDiagnostics.shared.log("RemoteClipboard", $0) })
    }

    static func cycle(
        targetPID: pid_t, ownPID: pid_t,
        frontmostPID: () -> pid_t?,
        activateOwn: () -> Bool, activateTarget: () -> Bool,
        canContinue: () -> Bool,
        pause: (UInt64) async -> Void,
        diagnose: (String) -> Void = { _ in }
    ) async -> Bool {
        func fail(_ reason: String) -> Bool {
            diagnose("focusRefresh=\(reason) frontmostPID=\(frontmostPID() ?? -1)")
            return false
        }
        guard targetPID != ownPID, frontmostPID() == targetPID,
              canContinue(), !Task.isCancelled else { return fail("invalidInitialTarget") }
        guard activateOwn() else { return fail("activationRejected") }
        // Activation is asynchronous. Bound both transitions, and stop if the
        // user selects another application while we are handing focus back.
        for _ in 0..<100 {
            if frontmostPID() == ownPID { break }
            guard frontmostPID() == targetPID else { return fail("userChangedApp") }
            await pause(20_000_000)
        }
        guard frontmostPID() == ownPID else { return fail("activationTimedOut") }
        diagnose("focusRefresh=ownAppActive")
        await pause(100_000_000)
        guard frontmostPID() == ownPID else { return fail("userChangedApp") }
        // Even after cancellation, return focus if we still own it. The caller
        // separately validates session, clipboard and the original target window.
        guard activateTarget() else { return fail("returnRejected") }
        for _ in 0..<100 {
            if frontmostPID() == targetPID {
                let valid = canContinue() && !Task.isCancelled
                diagnose("focusRefresh=returned deliveryValid=\(valid)")
                return valid
            }
            guard frontmostPID() == ownPID else { return fail("userChangedApp") }
            await pause(20_000_000)
        }
        return fail("returnTimedOut")
    }
